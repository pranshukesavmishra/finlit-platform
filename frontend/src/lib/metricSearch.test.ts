import { describe, expect, it } from "vitest";
import { approxIn, compact, searchMetrics, type Searchable } from "./metricSearch";

const L: Searchable[] = [
  { key: "pe", label: "P/E Ratio", groupLabel: "Valuation", say: "Rupees you pay for each rupee of yearly profit." },
  { key: "ev_cfo", label: "EV / CFO", groupLabel: "Valuation", say: "Enterprise value for each rupee of operating cash flow." },
  { key: "ev_ebitda", label: "EV / EBITDA", groupLabel: "Valuation", say: "Enterprise value for each rupee of operating earnings." },
  { key: "ev_sales", label: "EV / Sales", groupLabel: "Valuation", say: "" },
  { key: "price_cfo", label: "Price / CFO", groupLabel: "Valuation", say: "" },
  { key: "roe", label: "Return on equity", groupLabel: "Profitability", say: "Profit earned on shareholders' money." },
  { key: "roce", label: "Return on capital employed", groupLabel: "Profitability", say: "" },
  { key: "debt_to_equity", label: "Debt to equity", groupLabel: "Financial Health", say: "Rupees owed for every rupee of owners' money." },
  { key: "q_operating_profit", label: "Latest quarter operating profit", groupLabel: "Quarterly Results", say: "" },
  { key: "cfo", label: "Operating cash flow (latest year)", groupLabel: "Financial Health", say: "Cash generated by the business itself." },
];
const top = (q: string) => searchMetrics(L, q)[0]?.key;

describe("metric search", () => {
  it("ignores spaces and punctuation around the division sign", () => {
    for (const q of ["EV/CFO", "EV / CFO", "ev /cfo", "ev/ cfo", "ev   cfo", "evcfo", "EV-CFO"]) expect(top(q), q).toBe("ev_cfo");
  });
  it("finds by plain words and by the key", () => {
    expect(top("p/e")).toBe("pe");
    expect(top("operating profit")).toBe("q_operating_profit");
    expect(top("debt_to_equity")).toBe("debt_to_equity");
    expect(top("return on equity")).toBe("roe");
  });
  it("forgives small typos", () => {
    expect(top("retun on equty")).toBe("roe");
    expect(top("evcof")).toBe("ev_cfo");
    expect(top("opertaing profit")).toBe("q_operating_profit");
    expect(top("debt to equiy")).toBe("debt_to_equity");
  });
  it("finds through the hint text and the group", () => {
    expect(searchMetrics(L, "shareholders").map((m) => m.key)).toContain("roe");
    expect(searchMetrics(L, "valuation").length).toBeGreaterThanOrEqual(5);
  });
  it("returns nothing for nonsense and everything for an empty box", () => {
    expect(searchMetrics(L, "zzzzqq")).toEqual([]);
    expect(searchMetrics(L, "  ")).toHaveLength(L.length);
  });
  it("helpers", () => {
    expect(compact("EV / CFO")).toBe("evcfo");
    expect(compact("Debt & Equity")).toBe("debtandequity");
    expect(approxIn("operating", "opertaing", 2)).toBeLessThanOrEqual(2);
    expect(approxIn("abc", "xyz", 1)).toBe(2);
  });
});
